import type { Exercise, ExerciseCategory, MuscleGroup } from '../types';

// Compact helper so the 150+ list stays readable.
let n = 0;
function ex(
  name: string,
  category: ExerciseCategory,
  primary: MuscleGroup,
  secondary: MuscleGroup[],
  equipment: string,
  isCore = false,
): Exercise {
  n += 1;
  return {
    id: `${category.slice(0, 3).toLowerCase()}-${n}`,
    name,
    category,
    primary,
    secondary,
    equipment,
    isCore,
    // Public demo video placeholder — NFC pairing opens this.
    videoUrl: `https://www.youtube.com/results?search_query=${encodeURIComponent(name + ' form')}`,
  };
}

